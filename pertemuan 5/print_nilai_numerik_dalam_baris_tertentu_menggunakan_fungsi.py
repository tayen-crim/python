#fungsi oct
int1 = oct(140) 
print(f"int1: {int1}") 

int2 = oct(0x8c) 
print(f"int2: {int2}") 

#fungsi hex
int3 = hex(140) 
print(f"int3: {int3}") 

int4 = hex(0b10001100) 
print(f"int4: {int4}") 

#fungsi bin
int5 = bin(140) 
print(f"int5: {int5}")

int6 = bin(0o214) 
print(f"int6: {int6}")
