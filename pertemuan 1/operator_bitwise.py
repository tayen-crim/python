#Operator bitwise

x=1
y=1

hasil_1= x&y
print("x&y = 1", hasil_1)

hasil_2= x|y
print("x|y = 1", hasil_2)

hasil_3= -x
print("-x = -1", hasil_3)

hasil_4 = x^y
print("x^y = 1", hasil_4 ) 

hasil_5 = x >> 2
print("x >> 2 = 1", hasil_5)

hasil_6 = x << 2
print("x << 2 = 1", hasil_6)
